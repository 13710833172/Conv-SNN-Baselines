from __future__ import annotations

import argparse
import json
import shutil
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any


@dataclass
class RunSummary:
    dataset: str
    run_name: str
    run_dir: str
    epochs: int | None
    timesteps: int | None
    channels: int | None
    hidden_dim: int | None
    neuron: str | None
    amp: bool | None
    best_epoch: int | None
    best_val_acc: float | None
    final_val_acc: float | None
    test_acc: float | None
    test_loss: float | None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Collect experiment metadata from timestamped run directories."
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Repository root that contains runs/.",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=None,
        help="Output directory for summary JSON/Markdown. Defaults to <root>/results.",
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=None,
        help="Output directory for copied best-run curves. Defaults to <root>/assets/figures.",
    )
    return parser.parse_args()


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def _iter_run_dirs(runs_root: Path) -> list[Path]:
    run_dirs: list[Path] = []
    if not runs_root.exists():
        return run_dirs
    for dataset_dir in sorted(path for path in runs_root.iterdir() if path.is_dir()):
        for run_dir in sorted(path for path in dataset_dir.iterdir() if path.is_dir()):
            if (run_dir / "args.json").exists():
                run_dirs.append(run_dir)
    return run_dirs


def _collect_run_summary(repo_root: Path, run_dir: Path) -> RunSummary | None:
    args_payload = _read_json(run_dir / "args.json")
    metrics_payload = _read_json(run_dir / "metrics.json")
    test_payload = _read_json(run_dir / "test_metrics.json")

    if not args_payload or not metrics_payload:
        return None

    best_metrics = metrics_payload.get("best") or {}
    final_metrics = metrics_payload.get("final") or {}

    return RunSummary(
        dataset=str(args_payload.get("dataset", run_dir.parent.name)),
        run_name=run_dir.name,
        run_dir=str(run_dir.relative_to(repo_root)),
        epochs=_as_int(args_payload.get("epochs")),
        timesteps=_as_int(args_payload.get("timesteps")),
        channels=_as_int(args_payload.get("channels")),
        hidden_dim=_as_int(args_payload.get("hidden_dim")),
        neuron=_as_str(args_payload.get("neuron")),
        amp=_as_bool(args_payload.get("amp")),
        best_epoch=_as_int(best_metrics.get("epoch")),
        best_val_acc=_as_float(best_metrics.get("val_acc")),
        final_val_acc=_as_float(final_metrics.get("val_acc")),
        test_acc=_as_float(test_payload.get("test_acc")),
        test_loss=_as_float(test_payload.get("test_loss")),
    )


def _as_int(value: Any) -> int | None:
    if value is None:
        return None
    return int(value)


def _as_float(value: Any) -> float | None:
    if value is None:
        return None
    return float(value)


def _as_bool(value: Any) -> bool | None:
    if value is None:
        return None
    return bool(value)


def _as_str(value: Any) -> str | None:
    if value is None:
        return None
    return str(value)


def _score(summary: RunSummary) -> tuple[float, float, int]:
    test_score = summary.test_acc if summary.test_acc is not None else -1.0
    val_score = summary.best_val_acc if summary.best_val_acc is not None else -1.0
    epochs = summary.epochs if summary.epochs is not None else -1
    return (test_score, val_score, epochs)


def _format_pct(value: float | None) -> str:
    if value is None:
        return "-"
    return f"{value * 100:.2f}"


def _write_summary_json(path: Path, summaries: list[RunSummary]) -> None:
    payload = {"runs": [asdict(summary) for summary in summaries]}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)


def _write_summary_markdown(
    path: Path, summaries: list[RunSummary], best_by_dataset: dict[str, RunSummary]
) -> None:
    lines = [
        "# Experiment Summary",
        "",
        "This file is generated by `python scripts/summarize_runs.py`.",
        "",
        "## Best Runs by Dataset",
        "",
        "| Dataset | Run | Epochs | T | Channels | Hidden | Best Val (%) | Test (%) |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]

    for dataset in sorted(best_by_dataset):
        summary = best_by_dataset[dataset]
        lines.append(
            "| "
            + " | ".join(
                [
                    summary.dataset,
                    summary.run_name,
                    str(summary.epochs or "-"),
                    str(summary.timesteps or "-"),
                    str(summary.channels or "-"),
                    str(summary.hidden_dim or "-"),
                    _format_pct(summary.best_val_acc),
                    _format_pct(summary.test_acc),
                ]
            )
            + " |"
        )

    lines.extend(
        [
            "",
            "## All Recorded Runs",
            "",
            "| Dataset | Run | Epochs | T | Neuron | AMP | Best Epoch | Best Val (%) | Final Val (%) | Test (%) |",
            "| --- | --- | ---: | ---: | --- | --- | ---: | ---: | ---: | ---: |",
        ]
    )

    for summary in summaries:
        lines.append(
            "| "
            + " | ".join(
                [
                    summary.dataset,
                    summary.run_name,
                    str(summary.epochs or "-"),
                    str(summary.timesteps or "-"),
                    summary.neuron or "-",
                    "yes" if summary.amp else "no",
                    str(summary.best_epoch or "-"),
                    _format_pct(summary.best_val_acc),
                    _format_pct(summary.final_val_acc),
                    _format_pct(summary.test_acc),
                ]
            )
            + " |"
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def _copy_best_run_figures(
    repo_root: Path,
    figures_dir: Path,
    best_by_dataset: dict[str, RunSummary],
) -> None:
    figures_dir.mkdir(parents=True, exist_ok=True)
    for dataset, summary in best_by_dataset.items():
        source_run_dir = repo_root / summary.run_dir
        for figure_name in ("val_acc.svg", "train_loss.svg"):
            source = source_run_dir / figure_name
            if not source.exists():
                continue
            target = figures_dir / f"{dataset}_{figure_name}"
            shutil.copy2(source, target)


def main() -> None:
    args = parse_args()
    repo_root = args.root.resolve()
    results_dir = (
        args.results_dir.resolve()
        if args.results_dir is not None
        else repo_root / "results"
    )
    figures_dir = (
        args.figures_dir.resolve()
        if args.figures_dir is not None
        else repo_root / "assets" / "figures"
    )

    summaries = []
    for run_dir in _iter_run_dirs(repo_root / "runs"):
        summary = _collect_run_summary(repo_root, run_dir)
        if summary is not None:
            summaries.append(summary)

    summaries.sort(key=lambda item: (item.dataset, _score(item)), reverse=True)

    best_by_dataset: dict[str, RunSummary] = {}
    for summary in summaries:
        current_best = best_by_dataset.get(summary.dataset)
        if current_best is None or _score(summary) > _score(current_best):
            best_by_dataset[summary.dataset] = summary

    _write_summary_json(results_dir / "experiment_summary.json", summaries)
    _write_summary_markdown(results_dir / "experiment_summary.md", summaries, best_by_dataset)
    _copy_best_run_figures(repo_root, figures_dir, best_by_dataset)

    print(f"wrote {results_dir / 'experiment_summary.json'}")
    print(f"wrote {results_dir / 'experiment_summary.md'}")
    print(f"copied figures to {figures_dir}")


if __name__ == "__main__":
    main()
